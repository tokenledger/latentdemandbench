"""Generate the paper appendix containing the complete model I/O contract."""

import argparse
import hashlib
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ldb.llm import LEXICON, SCHEMA, SYSTEM, TASK  # noqa: E402


def _verbatim(text: str) -> str:
    if r"\end{Verbatim}" in text:
        raise ValueError("Verbatim terminator present in generated content")
    return (
        "\\begin{Verbatim}[breaklines=true,breakanywhere=true,"
        "breaksymbolleft={},breaksymbolright={},fontsize=\\scriptsize]\n"
        + text.rstrip()
        + "\n\\end{Verbatim}\n"
    )


def render() -> str:
    schema = json.dumps(SCHEMA, indent=2, ensure_ascii=False)
    lexicon = json.dumps(LEXICON, indent=2, ensure_ascii=False)
    digest = hashlib.sha256(
        (SYSTEM + "\0" + TASK + "\0" + schema + "\0" + lexicon).encode()
    ).hexdigest()[:16]
    parts = [
        "% generated by tools/prompt_appendix.py; do not edit\n",
        r"\section{Complete prompt and response contract}" + "\n",
        r"\label{sec:prompt}" + "\n",
        "This appendix is generated directly from the canonical strings and schema "
        "used by the harness (contract digest \\texttt{" + digest + "}). Runtime "
        "substitution fills the brace-delimited fields. The \\texttt{corpus} field "
        "is the complete generated dossier and \\texttt{probes} is the fixed list of "
        "pair identifiers for that universe.\n\n",
        r"\subsection{System prompt template}" + "\n",
        _verbatim(SYSTEM),
        r"\subsection{Surface lexicon substitutions}" + "\n",
        _verbatim(lexicon),
        r"\subsection{Task wrapper}" + "\n",
        _verbatim(TASK),
        r"\subsection{Canonical response schema}" + "\n",
        "The schema below is for $K=40$. At request time, the corrected harness "
        "sets the prediction list's \\texttt{maxItems} to $K$, "
        "including $K=90$ for the rerun large-economy arms. Archived small-economy "
        "calls used a schema limit of 40 but were scored at their requested "
        "$K=25$; their generation provenance is retained separately.\n",
        _verbatim(schema),
        r"\subsection{Backend-specific enforcement}" + "\n",
        "For the OpenAI frontier arms, the harness recursively marks every object "
        "closed and every declared property required, then sends the schema with "
        "strict structured output. It sends the rendered system template as "
        "\\texttt{instructions}, the rendered task as \\texttt{input}, reasoning "
        "effort \\texttt{medium}, and a 48{,}000-token output limit; it does not send "
        "temperature. For the reported vLLM arm, the canonical schema is supplied "
        "to guided decoding. If the decoder cannot compile all constraints, its "
        "fallback removes \\texttt{maxItems} and \\texttt{additionalProperties}, and "
        "then numeric bounds if required. The scorer independently enforces the "
        "top-$K$ cap, candidate validity and probability range.\n",
    ]
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="reproduced/prompt_appendix.tex")
    args = parser.parse_args()
    out = Path(args.out)
    if not out.is_absolute():
        out = ROOT / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render())
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
